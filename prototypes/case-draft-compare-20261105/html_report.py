#!/usr/bin/env python3
"""Optional static HTML reader for the existing offline case-draft comparator.

All JSON content is author-supplied and unverified. This module never performs
network requests, assigns ethical conclusions or modifies the two input files.
"""
import argparse
from collections import Counter
import html
from pathlib import Path
import sys

import compare

MAX_HTML_BYTES = 2 * 1024 * 1024
# Reserve room for the fixed page shell and labels while adding authored diffs.
HTML_FRAME_RESERVE = 8 * 1024


def _escape(value):
    return html.escape(value, quote=True)


def render_html(differences, before_hash, after_hash, summary=False):
    """Render a deterministic, inert HTML comparison without interpreting author text."""
    counts = Counter(op for op, _, _, _ in differences)
    # The operation names are generated by compare.changes, not user input.
    names = {
        'ADDED': 'Added author field',
        'REMOVED': 'Removed author field',
        'CHANGED': 'Changed author field',
        'REORDERED': 'Reordered exact row set',
    }
    if any(op not in names for op, _, _, _ in differences):
        raise compare.CompareError('unsupported comparison operation')
    cells = []
    detail_bytes = 0
    if summary:
        cells.append('<p>Summary only: author paths and values deliberately omitted.</p>')
    elif not differences:
        cells.append('<p>No JSON field changes. This is not evidence that real events remained unchanged.</p>')
    else:
        for i, (op, path, before, after) in enumerate(differences, 1):
            # All paths and values are first rendered as one-line JSON, then HTML escaped.
            path_text = _escape(compare._quote(path))
            old_text = _escape(compare._quote(before))
            new_text = _escape(compare._quote(after))
            extra = ('<p class="caution">No row identity is inferred; the same complete '
                     'row values were supplied in a different order.</p>' if op == 'REORDERED' else '')
            cell = (
                '<section class="change" aria-labelledby="change-' + str(i) + '">'
                '<h3 id="change-' + str(i) + '">' + names[op] + '</h3>'
                '<p class="type">' + op + ' · JSON Pointer <code>' + path_text + '</code></p>'
                '<div class="pair">'
                '<div><h4>Before (author data)</h4><pre><code>' + old_text + '</code></pre></div>'
                '<div><h4>After (author data)</h4><pre><code>' + new_text + '</code></pre></div>'
                '</div>' + extra + '</section>'
            )
            detail_bytes += len(cell.encode('utf-8'))
            if detail_bytes > MAX_HTML_BYTES - HTML_FRAME_RESERVE:
                raise compare.CompareError('HTML detail exceeds 2 MiB report budget; use --summary or a specialist diff')
            cells.append(cell)
    summary_line = ' · '.join(op + ': ' + str(counts[op]) for op in names)
    # Exact byte hashes are linkable identifiers of a private draft; even an
    # otherwise text-free summary should not expose them by default.
    fingerprint_block = (
        '<b>File fingerprints omitted in summary-only mode.</b>'
        '<p>Counts can still reveal information; inspect before sharing.</p>'
        if summary else
        '<b>File-byte fingerprints (not authorship proof)</b>'
        '<code>BEFORE_SHA256: ' + _escape(before_hash) + '</code>'
        '<code>AFTER_SHA256: ' + _escape(after_hash) + '</code>'
    )
    page = '''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Local case-draft comparison (unverified)</title>
<style>
:root{color-scheme:light;--ink:#202b37;--quiet:#4b5865;--line:#ccd6df;--tint:#f3f6f9}
*{box-sizing:border-box}body{margin:0;font:16px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif;color:var(--ink);background:white}
main{max-width:960px;margin:auto;padding:1.4rem 1.1rem 3rem}
h1{font-size:clamp(1.5rem,3.5vw,2rem);line-height:1.2}h2{font-size:1.25rem}h3{font-size:1.08rem}
h4{font-size:.9rem;margin:.4rem 0}p{margin:.6rem 0}.intro,.caution{color:var(--quiet)}
.meta{padding:.75rem;background:var(--tint);border:1px solid var(--line);border-radius:6px}
.meta code{display:block;overflow-wrap:anywhere;font-size:.8rem}.change{border:1px solid var(--line);border-radius:8px;padding:1rem;margin:1rem 0}
.type{font-size:.9rem}.type code{overflow-wrap:anywhere}.pair{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:.8rem}
pre{white-space:pre-wrap;overflow-wrap:anywhere;unicode-bidi:plaintext;margin:.3rem 0;background:var(--tint);padding:.7rem;min-height:3rem;border-radius:5px}
pre code{font-size:.88rem}footer{margin-top:2rem;border-top:1px solid var(--line);padding-top:.6rem;font-size:.86rem;color:var(--quiet)}
@media(max-width:620px){.pair{grid-template-columns:1fr}}
@media print{body{font-size:11pt}main{max-width:none;padding:0}.change{break-inside:avoid}}
</style></head><body><main>
<header><h1>Local case-draft comparison</h1>
<p class="intro">Comparison of author-supplied JSON only. It does not verify events, witnesses, claims, evidence labels, permissions, outcomes or correction reachability. If a specialist record or ordinary document diff is more suitable, use it.</p>
<div class="meta">''' + fingerprint_block + '''
<p>''' + _escape(summary_line) + '''</p></div>
<p class="caution">Absent is different from null and from an explicit unknown. Field changes are not proof that the world changed. Lists compare by position unless the optional exact-row-moves mode is requested.</p>
</header><h2>Authored differences</h2>
''' + '\n'.join(cells) + '''
<footer>No scripts, external resources, uploads or telemetry. This optional static report contains private author text unless summary-only mode was chosen. REORDERED means the same complete rows changed order, not that people or events were identified. Case-card schema validity is not checked here.</footer>
</main></body></html>\n'''
    if len(page.encode('utf-8')) > MAX_HTML_BYTES:
        raise compare.CompareError('HTML report exceeds 2 MiB budget; use --summary or a specialist diff')
    return page


def main(argv=None):
    parser = argparse.ArgumentParser(description='Read two local author-held JSON drafts as a static HTML diff')
    parser.add_argument('before', help='older author draft JSON')
    parser.add_argument('after', help='newer author draft JSON')
    parser.add_argument('--summary', action='store_true', help='omit author paths, values and file hashes; counts can still reveal information')
    parser.add_argument('--exact-row-moves', action='store_true', help='identify pure whole-row permutations')
    parser.add_argument('--output', '-o', help='atomically write a static HTML report (default stdout)')
    args = parser.parse_args(argv)
    try:
        if args.output and Path(args.output).resolve() in {
                Path(args.before).resolve(), Path(args.after).resolve()}:
            raise compare.CompareError('output must not overwrite either input')
        a, b = compare._read(args.before), compare._read(args.after)
        report = render_html(
            compare.changes(compare.parse_json(a), compare.parse_json(b), args.exact_row_moves),
            compare.sha256(a), compare.sha256(b), args.summary,
        )
        if args.output:
            compare._atomic(args.output, report)
        else:
            sys.stdout.write(report)
        return 0
    except (compare.CompareError, OSError, UnicodeError, RecursionError) as exc:
        print('case-compare-html: ' + str(exc), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
